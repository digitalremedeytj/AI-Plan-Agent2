import { AudienceProfile, GeoTargeting } from "../types";
import { geoCoverage } from "../planning/geoTargeting";
import { effectiveBriefSections } from "../research/executiveBriefSlides";

export function exportProfileToMarkdown(
  profile: AudienceProfile,
  includeSources: boolean = true,
  includeAudit: boolean = true,
  // The footprint is brief input rather than part of the profile, so it is passed in.
  geoTargeting?: GeoTargeting
): string {
  const dateStr = new Date().toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric"
  });

  let markdown = `# Audience Profile: Media Planning & Strategic Report\n`;
  markdown += `*Generated by Audience Profile Builder — ${dateStr}*\n\n`;

  const hidden = new Set(profile.hiddenSections || []);

  // What failed or was not found travels with the export, the same as on screen.
  if (profile.generationAlerts && profile.generationAlerts.length > 0) {
    markdown += `## Items That Did Not Complete\n\n`;
    profile.generationAlerts.forEach(alert => {
      const label = alert.severity === "failed" ? "Failed" : alert.severity === "not_found" ? "Not found" : "Check";
      markdown += `- **${label}**: ${alert.message}\n`;
    });
    markdown += `\n`;
  }

  // Intro
  if (!hidden.has("intro")) {
    markdown += `## Strategic Introduction\n\n`;
    markdown += `### Audience Overview\n`;
    markdown += `${profile.intro}\n\n`;
    if (profile.audienceAnalysis && profile.audienceAnalysis.trim()) {
      markdown += `### Audience Analysis\n`;
      markdown += `${profile.audienceAnalysis}\n\n`;
    }
  }

  // Key Personas
  if (!hidden.has("personas")) {
    markdown += `## Target Audience Personas\n\n`;
    if (profile.expansionReachPercent) {
      markdown += `> **ScoutAI Expansion Audience Note**: Personas marked ScoutAI are recommended expansion audiences, estimated to increase addressable reach by approximately ${profile.expansionReachPercent}%.\n\n`;
    }
    profile.personas.forEach((persona, idx) => {
      const label = persona.sourceType ? ` [${persona.sourceType}]` : "";
      markdown += `### Persona ${idx + 1}: ${persona.name}${label}\n`;
      markdown += `- **Demographics**: Age ${persona.age} | ${persona.gender} | Income ${persona.income}\n`;
      markdown += `- **Media consumption (Watch)**: ${persona.watch}\n`;
      markdown += `- **Online activities (Browse)**: ${persona.browse}\n`;
      markdown += `- **Shopping behaviors (Buy)**: ${persona.buy}\n\n`;
      markdown += `> **Archetype Narrative**:\n`;
      markdown += `> ${persona.narrative}\n\n`;
    });
  }

  // Segment Recommendations (if present)
  if (!hidden.has("segments") && profile.segmentRecommendations && profile.segmentRecommendations.length > 0) {
    markdown += `## Segment Recommendations\n\n`;
    markdown += `| Segment Name | Dimension | Justification |\n`;
    markdown += `| :--- | :--- | :--- |\n`;
    profile.segmentRecommendations.forEach(segment => {
      markdown += `| ${segment.name} | ${segment.dimension} | ${segment.justification || "Audience alignment"} |\n`;
    });
    markdown += `\n`;
  }

  // Key Insights & Recommendations (Core Takeaways + Strategic Recommendations)
  if (!hidden.has("insights")) {
    markdown += `## Key Insights & Recommendations\n\n`;
    markdown += `### Core Audience Takeaways\n`;
    profile.takeaways.forEach((takeaway, idx) => {
      markdown += `${idx + 1}. **${takeaway}**\n`;
    });
    markdown += `\n`;

    markdown += `### Strategic Media Recommendations\n`;
    profile.recommendations.forEach((rec, idx) => {
      markdown += `#### Recommendation ${idx + 1}: ${rec.title}\n`;
      markdown += `- **Strategic Action**: ${rec.action}\n`;
      markdown += `- **Planning Justification**: ${rec.why}\n`;
      markdown += `- **Primary Activation Channels**: ${rec.channels}\n\n`;
    });
  }

  // Browser and reach
  if (!hidden.has("domainAffinity")) {
    markdown += `## Domain Affinity Index\n\n`;
    markdown += `${profile.browserAndReach.overview}\n\n`;
    markdown += `#### Top Domain Affinity Index\n`;
    if (!profile.browserAndReach.chartData || profile.browserAndReach.chartData.length === 0) {
      markdown += `*Not found in research.*\n`;
    } else {
      markdown += `| Domain | Affinity Index |\n`;
      markdown += `| :--- | :--- |\n`;
      profile.browserAndReach.chartData.forEach(item => {
        markdown += `| ${item.domain} | ${item.value}% |\n`;
      });
    }
    markdown += `\n*Source: ${profile.browserAndReach.chartSource}*\n\n`;
  }

  // Device type index
  if (!hidden.has("deviceSplit") && !hidden.has("deviceShare")) {
    markdown += `## Device and Platform Split\n\n`;
    markdown += `${profile.deviceTypeIndex.overview}\n\n`;
    markdown += `#### Device Composition Share\n`;
    if (!profile.deviceTypeIndex.chartData || profile.deviceTypeIndex.chartData.length === 0) {
      markdown += `*Not found in research.*\n`;
    } else {
      markdown += `| Device / Platform | Split Share % | Source |\n`;
      markdown += `| :--- | :--- | :--- |\n`;
      profile.deviceTypeIndex.chartData.forEach(item => {
        markdown += `| ${item.device} | ${item.value}% | ${item.source || "Not stated"} |\n`;
      });
    }
    markdown += `\n*Source: ${profile.deviceTypeIndex.chartSource}*\n\n`;
  }

  // Audience demographic and geography
  if (!hidden.has("demographics")) {
    markdown += `## Demographics & Geographic Concentration\n\n`;
    markdown += `${profile.demographics.overview}\n\n`;
    
    markdown += `#### Age Profile Breakdown\n`;
    if (!profile.demographics.ageChartData || profile.demographics.ageChartData.length === 0) {
      markdown += `*Not found in research.*\n`;
    } else {
      markdown += `| Age Bracket | Composition Share % |\n`;
      markdown += `| :--- | :--- |\n`;
      profile.demographics.ageChartData.forEach(item => {
        markdown += `| ${item.range} | ${item.value}% |\n`;
      });
    }
    markdown += `\n`;

    markdown += `#### Household Income (HHI) Breakdown\n`;
    if (!profile.demographics.incomeChartData || profile.demographics.incomeChartData.length === 0) {
      markdown += `*Not found in research.*\n`;
    } else {
      markdown += `| Income Range | Composition Share % |\n`;
      markdown += `| :--- | :--- |\n`;
      profile.demographics.incomeChartData.forEach(item => {
        markdown += `| ${item.bracket} | ${item.value}% |\n`;
      });
    }
    markdown += `\n`;

    markdown += `#### Geographic & Regional Footprint\n`;
    markdown += `${profile.demographics.geographyNotes}\n\n`;
  }

  // Geo targeting footprint. Coverage is stated only where the data supports it: state
  // targeting gets market overlap, because rolling multi-state markets up to states would
  // count the same households several times.
  const geoCoverageSummary = geoTargeting ? geoCoverage(geoTargeting) : null;
  if (!hidden.has("geoFootprint") && geoTargeting && geoCoverageSummary) {
    markdown += `## Geo Targeting Footprint\n\n`;
    if (geoCoverageSummary.scope === "dma") {
      markdown += `**${geoCoverageSummary.marketCount} DMAs** covering ${geoCoverageSummary.tvHouseholds.toLocaleString()} TV households (${geoCoverageSummary.usSharePct.toFixed(1)}% of US), delivering into ${geoCoverageSummary.states.length} states.\n\n`;
      markdown += `| Rank | Market | DMA Code | TV Households | States |\n`;
      markdown += `| :--- | :--- | :--- | :--- | :--- |\n`;
      geoTargeting.entries.forEach(entry => {
        markdown += `| ${entry.rank} | ${entry.name} | ${entry.id} | ${(entry.tvHouseholds || 0).toLocaleString()} | ${(entry.states || []).join(", ")} |\n`;
      });
      markdown += `\n`;
    } else {
      markdown += `**${geoCoverageSummary.stateCount} states**, served by ${geoCoverageSummary.overlappingDmaCount} DMAs.\n\n`;
      markdown += `States: ${geoTargeting.entries.map(entry => `${entry.name} (${entry.id})`).join(", ")}\n\n`;
      if (geoCoverageSummary.spillMarketCount > 0) {
        markdown += `*Market spill: ${geoCoverageSummary.spillMarketCount} of those markets also deliver into ${geoCoverageSummary.spillStates.length} neighbouring states (${geoCoverageSummary.spillStates.join(", ")}).*\n\n`;
      }
    }
    if (profile.geoInsights && profile.geoInsights.trim().length > 0) {
      markdown += `#### Geo Insights\n`;
      markdown += `${profile.geoInsights}\n\n`;
    }
  }

  // Temporal patterns
  if (!hidden.has("daypart") && !hidden.has("temporal")) {
    markdown += `## Temporal Activity & Daypart Strategy\n\n`;
    markdown += `${profile.temporalPatterns.overview}\n\n`;

    markdown += `#### Day of Week Activity Indices (100 is Average Baseline)\n`;
    if (!profile.temporalPatterns.dayOfWeekChartData || profile.temporalPatterns.dayOfWeekChartData.length === 0) {
      markdown += `*Not found in research.*\n`;
    } else {
      markdown += `| Day of Week | Relative Activity Index |\n`;
      markdown += `| :--- | :--- |\n`;
      profile.temporalPatterns.dayOfWeekChartData.forEach(item => {
        markdown += `| ${item.day} | ${item.index} |\n`;
      });
    }
    markdown += `\n`;

    markdown += `#### Activation Notes & Buying Window Alignment\n`;
    markdown += `${profile.temporalPatterns.activationNotes}\n\n`;
  }

  // Channel Strategy & Activation Plan (if present)
  if (!hidden.has("channels") && profile.channelStrategy) {
    markdown += `## Channel Strategy & Activation Plan\n\n`;
    if (profile.channelStrategy.executiveInsight) {
      markdown += `### Executive Channel Strategy Insight\n`;
      markdown += `${profile.channelStrategy.executiveInsight}\n\n`;
    }
    const mediaPlan = profile.channelStrategy.mediaPlan;
    if (mediaPlan) {
      markdown += `### Planning Summary\n`;
      markdown += `- **Working Media Budget**: $${mediaPlan.workingMediaBudget.toLocaleString()}\n`;
      markdown += `- **Flight Length**: ${mediaPlan.flightDays ? `${mediaPlan.flightDays} days` : 'Not supplied'}\n`;
      markdown += `- **Normalized 30-Day Budget**: $${mediaPlan.normalized30DayBudget.toLocaleString(undefined, { maximumFractionDigits: 0 })}\n`;
      markdown += `- **Media-Type Cap / Selected**: ${mediaPlan.maxMediaTypes} / ${mediaPlan.selectedMediaTypeCount}\n`;
      markdown += `- **Planning Mode**: ${mediaPlan.planningMode}\n`;
      markdown += `- **Catalog / Settings Version**: ${mediaPlan.catalogVersion} / ${mediaPlan.settingsVersion}\n\n`;
      markdown += `### Validated Channel Allocations\n`;
      const channelOverrides = profile.channelStrategy.channelOverrides;
      mediaPlan.channels.forEach(channel => {
        const displayedStatus = String(channel.status) === 'CONDITIONAL' ? 'TEST' : channel.status;
        markdown += `- **${channel.channelName}** — ${channel.allocationPercent.toFixed(0)}% ($${channel.allocationDollars.toLocaleString()}); ${displayedStatus}, score ${channel.recommendationScore}/100, ${channel.confidence} confidence\n`;

        const overrides = channelOverrides?.[channel.channelId];
        const hidden = overrides?.hiddenPanels || [];
        const edits = overrides?.fieldEdits || {};

        if (!hidden.includes('gapAddressed')) {
          const gapTitle = edits['gapAddressed']?.title ?? 'Role / Gap';
          const gapContent = edits['gapAddressed']?.content ?? channel.gapAddressed;
          markdown += `  - **${gapTitle}**: ${channel.role ? `${channel.role}; ` : ''}${gapContent}\n`;
        }

        if (!hidden.includes('targetingTactics')) {
          const actTitle = edits['targetingTactics']?.title ?? 'Activation';
          const actContent = edits['targetingTactics']?.content ?? (channel.targetingTactics.map(item => item.displayName).join(', ') || 'Confirm compatible targeting');
          markdown += `  - **${actTitle}**: ${actContent}\n`;
        }

        if (!hidden.includes('measurementCapabilities')) {
          const measTitle = edits['measurementCapabilities']?.title ?? 'Measurement';
          const measContent = edits['measurementCapabilities']?.content ?? (channel.measurementCapabilities.map(item => item.displayName).join(', ') || 'Confirm eligible measurement');
          markdown += `  - **${measTitle}**: ${measContent}\n`;
        }

        if (!hidden.includes('planningRationale')) {
          const ratTitle = edits['planningRationale']?.title ?? 'Allocation Rationale';
          const ratContent = edits['planningRationale']?.content ?? channel.allocationRationale;
          markdown += `  - **${ratTitle}**: ${ratContent}\n`;
        }

        if (!hidden.includes('decisionRule')) {
          const ruleTitle = edits['decisionRule']?.title ?? 'Scale / Stop Rule';
          const ruleContent = edits['decisionRule']?.content ?? channel.decisionRule;
          markdown += `  - **${ruleTitle}**: ${ruleContent}\n`;
        }

        if (!hidden.includes('publishers') && channel.publishers && channel.publishers.length > 0) {
          const pubTitle = edits['publishers']?.title ?? 'Publishers';
          const pubContent = edits['publishers']?.content ?? channel.publishers.map(item => item.displayName).join(', ');
          markdown += `  - **${pubTitle}**: ${pubContent}\n`;
        }

        if (channel.prerequisites.length > 0) markdown += `  - **Prerequisites**: ${channel.prerequisites.join('; ')}\n`;
      });
      markdown += `\n`;
    }
    if (profile.channelStrategy.rfpChannels?.length > 0) {
      markdown += `### RFP & Evaluation Media Channels\n`;
      profile.channelStrategy.rfpChannels.forEach(c => {
        markdown += `- **${c.channelName}** (Score: ${c.score.toFixed(1)}/10 | Audience Fit: ${c.audienceFit}/10 | Goal Match: ${c.goalMatch}/10)\n`;
        markdown += `  - **Evidence**: ${c.mediaConsumptionEvidence}\n`;
        markdown += `  - **Strategic Value**: ${c.whyItEarnsASpot}\n`;
      });
      markdown += `\n`;
    }
    if (profile.channelStrategy.scoutAiRecommendedChannels?.length > 0) {
      markdown += `### ScoutAI Channel Expansion Recommendations\n`;
      profile.channelStrategy.scoutAiRecommendedChannels.forEach(c => {
        markdown += `- **${c.channelName}** (Score: ${c.score.toFixed(1)}/10 | Audience Fit: ${c.audienceFit}/10 | Goal Match: ${c.goalMatch}/10)\n`;
        markdown += `  - **Evidence**: ${c.mediaConsumptionEvidence}\n`;
        markdown += `  - **Strategic Value**: ${c.whyItEarnsASpot}\n`;
      });
      markdown += `\n`;
    }
  }

  // Executive Summary Blueprint (placed after Channel Strategy)
  // The executive brief as the planner left it (hand edits, hidden panels). Plans saved before
  // the brief keep their one-paragraph summary until upgraded.
  if (!hidden.has("blueprint") && !hidden.has("executiveSummary")) {
    const briefSections = profile.executiveBrief ? effectiveBriefSections(profile.executiveBrief) : [];
    if (briefSections.length > 0) {
      markdown += `## Executive Summary Blueprint\n\n`;
      for (const section of briefSections) {
        markdown += `### ${section.title}\n`;
        if (section.headline) markdown += `**${section.headline}**\n\n`;
        for (const b of section.bullets) markdown += `- ${b.lead ? `**${b.lead}**: ` : ""}${b.text}\n`;
        for (const c of section.structured?.channels || []) markdown += `- ${c.channelName} (${c.allocationPercent}%, ${c.funnelRole}): ${c.role}\n`;
        for (const m of section.structured?.measurement || []) markdown += `- ${m.capability}${m.proves ? `: ${m.proves}` : ""}\n`;
        markdown += `\n`;
      }
    } else if (profile.executiveSummary) {
      markdown += `## Executive Summary Blueprint\n\n`;
      markdown += `### Audience Opportunity & Channel Strategy Alignment\n`;
      markdown += `${profile.executiveSummary}\n\n`;
    }
  }

  // Citations
  if (includeSources && !hidden.has("sources")) {
    markdown += `## Citations\n\n`;
    profile.sources.forEach((source, idx) => {
      markdown += `### [Source ${idx + 1}] ${source.name}\n`;
      // A first-party source has no public URL to verify against, so the line is omitted
      // rather than rendered as an empty link.
      if (source.url) {
        markdown += `- **Verification URL**: [${source.url}](${source.url})\n`;
      }
      markdown += `- **Data Supported**: ${source.supportedClaims}\n`;
      markdown += `- **Authority Classification**: ${source.tier}\n`;
      markdown += `- **Media Plan Usage**: ${source.usageType}\n\n`;
    });
  }

  // QA Audit Scorecard
  if (includeAudit && profile.auditResult && !hidden.has("qaAudit")) {
    markdown += `## Programmatic Media Buyer QA Audit & Compliance Report\n\n`;
    markdown += `### Executive QA Summary\n`;
    markdown += `> ${profile.auditResult.executiveSummary}\n\n`;
    markdown += `- **Overall Media Planning Score**: **${profile.auditResult.finalScore}/100** ${profile.auditResult.originalScore !== profile.auditResult.finalScore ? `(Remediated from ${profile.auditResult.originalScore}/100)` : ""}\n`;
    // States what happened, never an approval the pipeline did not give.
    const qaStatus = profile.auditResult.qaBypassed
      ? "Not scored - the QA agent did not run"
      : profile.auditResult.remediationApplied
        ? "Scored, then auto-remediated (the remediated version was not re-scored)"
        : "Scored; no remediation was run";
    markdown += `- **Status**: ${qaStatus}\n\n`;
    
    markdown += `#### Evaluation Category Scores\n`;
    markdown += `| Evaluation Category | Score | Notes |\n`;
    markdown += `| :--- | :---: | :--- |\n`;
    profile.auditResult.scorecard.forEach(item => {
      markdown += `| ${item.category} | **${item.score}/20** | ${item.notes} |\n`;
    });
    markdown += `\n`;

    markdown += `#### Strategic Highlights\n`;
    profile.auditResult.strategicHighlights.forEach(hl => {
      markdown += `- ✔ ${hl}\n`;
    });
    markdown += `\n`;

    markdown += `#### Critical Red Flags\n`;
    (profile.auditResult.criticalRedFlags || []).forEach(flag => {
      markdown += `- ${flag}\n`;
    });
    markdown += `\n`;

    markdown += `#### AI Auto-Fix Actions\n`;
    if (profile.auditResult.autoFixes && profile.auditResult.autoFixes.length > 0) {
      profile.auditResult.autoFixes.forEach(fix => {
        markdown += `- **Issue**: ${fix.issue}\n`;
        markdown += `  - **AI Resolution**: *${fix.resolution}*\n`;
      });
    } else {
      markdown += `*No auto-fixes were applied.*\n`;
    }
    markdown += `\n`;
  }

  // Additional RFP Requirements & Agency Capability Responses
  if (!hidden.has("rfpRequirements") && profile.additionalRfpRequirements) {
    const rfp = profile.additionalRfpRequirements;
    markdown += `## Additional RFP Requirements & Agency Capability Responses\n\n`;

    if (rfp.rfpSummary) {
      markdown += `### RFP Executive Summary & Scope\n`;
      markdown += `${rfp.rfpSummary}\n\n`;
    }

    if (rfp.extractedMetadata) {
      const meta = rfp.extractedMetadata;
      markdown += `### Campaign Operational & Administrative Specifications\n`;
      if (meta.submissionDueDate) markdown += `- **Submission Due Date**: ${meta.submissionDueDate}\n`;
      if (meta.flightDates) markdown += `- **Flight Dates**: ${meta.flightDates}\n`;
      if (meta.budget) markdown += `- **Campaign Budget**: $${meta.budget.toLocaleString()}\n`;
      if (meta.paymentTerms) markdown += `- **Payment / Invoicing Terms**: ${meta.paymentTerms}\n`;
      if (meta.reportingRequirements && meta.reportingRequirements.length > 0) {
        markdown += `- **Reporting Schedule**: ${meta.reportingRequirements.join(", ")}\n`;
      }
      markdown += `\n`;
    }

    if (rfp.digitalRemedyCapabilityMatches && rfp.digitalRemedyCapabilityMatches.length > 0) {
      markdown += `### Specific RFP Questions & Digital Remedy Solutions\n\n`;
      rfp.digitalRemedyCapabilityMatches.forEach((match, i) => {
        markdown += `#### Ask ${i + 1}: ${match.rfpAsk}\n`;
        markdown += `- **Digital Remedy Solution**: ${match.digitalRemedySolution}\n`;
        markdown += `- **Execution & Capability Details**: ${match.capabilityDetails}\n`;
        markdown += `- **Capability Verification**: ${match.isSupported ? "Supported / Certified" : "Custom Configuration Required"}\n\n`;
      });
    }

    if (rfp.additionalNotes) {
      markdown += `### Additional RFP Process & Strategic Guidelines\n`;
      markdown += `${rfp.additionalNotes}\n\n`;
    }
  }

  return markdown;
}

export function exportSourcesToMarkdown(profile: AudienceProfile): string {
  let markdown = `# Citations & Sourcing Registry\n\n`;
  profile.sources.forEach((source, idx) => {
    markdown += `### [Source ${idx + 1}] ${source.name}\n`;
    if (source.url) {
      markdown += `- **URL**: ${source.url}\n`;
    }
    markdown += `- **Supported Claim**: ${source.supportedClaims}\n`;
    markdown += `- **Tier**: ${source.tier}\n`;
    markdown += `- **Usage**: ${source.usageType}\n\n`;
  });
  return markdown;
}
