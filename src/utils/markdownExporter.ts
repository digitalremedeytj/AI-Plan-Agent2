import { AudienceProfile } from "../types";

export function exportProfileToMarkdown(
  profile: AudienceProfile,
  includeSources: boolean = true,
  includeAudit: boolean = true
): string {
  const dateStr = new Date().toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric"
  });

  let markdown = `# Audience Profile: Media Planning & Strategic Report\n`;
  markdown += `*Generated by Audience Profile Builder — ${dateStr}*\n\n`;

  // 1. Intro
  markdown += `## 1. Strategic Introduction\n\n`;
  markdown += `### Audience Overview\n`;
  markdown += `${profile.intro}\n\n`;
  if (profile.audienceAnalysis && profile.audienceAnalysis.trim()) {
    markdown += `### Audience Analysis\n`;
    markdown += `${profile.audienceAnalysis}\n\n`;
  }

  // 2. Key Personas
  markdown += `## 2. Target Audience Personas\n\n`;
  if (profile.expansionReachPercent) {
    markdown += `> **ScoutAI Expansion Audience Note**: ScoutAI are recommended expansion audiences increases addressable reach by approximately ${profile.expansionReachPercent}%.\n\n`;
  }
  profile.personas.forEach((persona, idx) => {
    const label = persona.sourceType ? ` [${persona.sourceType}]` : "";
    markdown += `### Persona ${idx + 1}: ${persona.name}${label}\n`;
    markdown += `- **Demographics**: Age ${persona.age} | ${persona.gender} | Income ${persona.income}\n`;
    markdown += `- **Media consumption (Watch)**: ${persona.watch}\n`;
    markdown += `- **Online activities (Browse)**: ${persona.browse}\n`;
    markdown += `- **Shopping behaviors (Buy)**: ${persona.buy}\n\n`;
    markdown += `> **Archetype Narrative**:\n`;
    markdown += `> ${persona.narrative}\n\n`;
  });

  // 3. Key Takeaways
  markdown += `## 3. Core Audience Takeaways\n\n`;
  profile.takeaways.forEach((takeaway, idx) => {
    markdown += `${idx + 1}. **${takeaway}**\n`;
  });
  markdown += `\n`;

  // 4. Strategic Recommendations
  markdown += `## 4. Strategic Media Recommendations\n\n`;
  profile.recommendations.forEach((rec, idx) => {
    markdown += `### Recommendation ${idx + 1}: ${rec.title}\n`;
    markdown += `- **Strategic Action**: ${rec.action}\n`;
    markdown += `- **Planning Justification**: ${rec.why}\n`;
    markdown += `- **Primary Activation Channels**: ${rec.channels}\n\n`;
  });

  // 5. Browser and reach
  markdown += `## 5. Domain Affinity Index\n\n`;
  markdown += `${profile.browserAndReach.overview}\n\n`;
  markdown += `#### Top Domain Affinity Index\n`;
  markdown += `| Domain | Affinity Index |\n`;
  markdown += `| :--- | :--- |\n`;
  profile.browserAndReach.chartData.forEach(item => {
    markdown += `| ${item.domain} | ${item.value}% |\n`;
  });
  markdown += `\n*Source: ${profile.browserAndReach.chartSource}*\n\n`;

  // 6. Device type index
  markdown += `## 6. Device and Platform Split\n\n`;
  markdown += `${profile.deviceTypeIndex.overview}\n\n`;
  markdown += `#### Device Composition Share\n`;
  markdown += `| Device / Platform | Split Share % | Source Type |\n`;
  markdown += `| :--- | :--- | :--- |\n`;
  profile.deviceTypeIndex.chartData.forEach(item => {
    markdown += `| ${item.device} | ${item.value}% | ${item.isModeled ? "Modeled Proxy" : "Syndicated"} |\n`;
  });
  markdown += `\n*Source: ${profile.deviceTypeIndex.chartSource}*\n\n`;

  // 7. Audience demographic and geography
  markdown += `## 7. Demographics & Geographic Concentration\n\n`;
  markdown += `${profile.demographics.overview}\n\n`;
  
  markdown += `#### Age Profile Breakdown\n`;
  markdown += `| Age Bracket | Composition Share % |\n`;
  markdown += `| :--- | :--- |\n`;
  profile.demographics.ageChartData.forEach(item => {
    markdown += `| ${item.range} | ${item.value}% |\n`;
  });
  markdown += `\n`;

  markdown += `#### Household Income (HHI) Breakdown\n`;
  markdown += `| Income Range | Composition Share % |\n`;
  markdown += `| :--- | :--- |\n`;
  profile.demographics.incomeChartData.forEach(item => {
    markdown += `| ${item.bracket} | ${item.value}% |\n`;
  });
  markdown += `\n`;

  markdown += `#### Geographic & Regional Footprint\n`;
  markdown += `${profile.demographics.geographyNotes}\n\n`;

  // 8. Temporal patterns
  markdown += `## 8. Temporal Activity & Daypart Strategy\n\n`;
  markdown += `${profile.temporalPatterns.overview}\n\n`;

  markdown += `#### Day of Week Activity Indices (100 is Average Baseline)\n`;
  markdown += `| Day of Week | Relative Activity Index |\n`;
  markdown += `| :--- | :--- |\n`;
  profile.temporalPatterns.dayOfWeekChartData.forEach(item => {
    markdown += `| ${item.day} | ${item.index} |\n`;
  });
  markdown += `\n`;

  markdown += `#### Activation Notes & Buying Window Alignment\n`;
  markdown += `${profile.temporalPatterns.activationNotes}\n\n`;

  // 9. Executive summary
  markdown += `## 9. Executive Summary\n\n`;
  markdown += `${profile.executiveSummary}\n\n`;

  let sectionIndex = 10;

  // 10. Channel Strategy & Activation Plan (if present)
  if (profile.channelStrategy) {
    markdown += `## ${sectionIndex}. Channel Strategy & Activation Plan\n\n`;
    sectionIndex++;
    if (profile.channelStrategy.executiveInsight) {
      markdown += `### Executive Channel Strategy Insight\n`;
      markdown += `${profile.channelStrategy.executiveInsight}\n\n`;
    }
    if (profile.channelStrategy.rfpChannels?.length > 0) {
      markdown += `### RFP & Evaluation Media Channels\n`;
      profile.channelStrategy.rfpChannels.forEach(c => {
        markdown += `- **${c.channelName}** (Score: ${c.score.toFixed(1)}/10 | Audience Fit: ${c.audienceFit}/10 | Goal Match: ${c.goalMatch}/10)\n`;
        markdown += `  - **Evidence**: ${c.mediaConsumptionEvidence}\n`;
        markdown += `  - **Strategic Value**: ${c.whyItEarnsASpot}\n`;
      });
      markdown += `\n`;
    }
    if (profile.channelStrategy.scoutAiRecommendedChannels?.length > 0) {
      markdown += `### ScoutAI Channel Expansion Recommendations\n`;
      profile.channelStrategy.scoutAiRecommendedChannels.forEach(c => {
        markdown += `- **${c.channelName}** (Score: ${c.score.toFixed(1)}/10 | Audience Fit: ${c.audienceFit}/10 | Goal Match: ${c.goalMatch}/10)\n`;
        markdown += `  - **Evidence**: ${c.mediaConsumptionEvidence}\n`;
        markdown += `  - **Strategic Value**: ${c.whyItEarnsASpot}\n`;
      });
      markdown += `\n`;
    }
  }

  // Citations & Media Sourcing Registry
  if (includeSources) {
    markdown += `## ${sectionIndex}. Citations & Media Sourcing Registry\n\n`;
    sectionIndex++;
    profile.sources.forEach((source, idx) => {
      markdown += `### [Source ${idx + 1}] ${source.name}\n`;
      markdown += `- **Verification URL**: [${source.url}](${source.url})\n`;
      markdown += `- **Data Supported**: ${source.supportedClaims}\n`;
      markdown += `- **Authority Classification**: ${source.tier}\n`;
      markdown += `- **Media Plan Usage**: ${source.usageType}\n\n`;
    });
  }

  // QA Audit Scorecard
  if (includeAudit && profile.auditResult) {
    markdown += `## ${sectionIndex}. Programmatic Media Buyer QA Audit & Compliance Report\n\n`;
    sectionIndex++;
    markdown += `### Executive QA Summary\n`;
    markdown += `> ${profile.auditResult.executiveSummary}\n\n`;
    markdown += `- **Overall Media Planning Score**: **${profile.auditResult.finalScore}/100** ${profile.auditResult.originalScore !== profile.auditResult.finalScore ? `(Remediated from ${profile.auditResult.originalScore}/100)` : ""}\n`;
    markdown += `- **Status**: ${profile.auditResult.autoFixes && profile.auditResult.autoFixes.length > 0 ? "Auto-Corrected & Pristine Approved" : "Verified Client-Ready Approved"}\n\n`;
    
    markdown += `#### Evaluation Category Scores\n`;
    markdown += `| Evaluation Category | Score | Notes |\n`;
    markdown += `| :--- | :---: | :--- |\n`;
    profile.auditResult.scorecard.forEach(item => {
      markdown += `| ${item.category} | **${item.score}/20** | ${item.notes} |\n`;
    });
    markdown += `\n`;

    markdown += `#### Strategic Highlights\n`;
    profile.auditResult.strategicHighlights.forEach(hl => {
      markdown += `- ✔ ${hl}\n`;
    });
    markdown += `\n`;

    markdown += `#### Critical Red Flags & AI Auto-Fix Actions\n`;
    if (profile.auditResult.autoFixes && profile.auditResult.autoFixes.length > 0) {
      profile.auditResult.autoFixes.forEach(fix => {
        markdown += `- **Issue**: ${fix.issue}\n`;
        markdown += `  - **AI Resolution**: *${fix.resolution}*\n`;
      });
    } else {
      markdown += `*Clean - No major data hallucinations or metric contradictions detected during QA evaluation.*\n`;
    }
    markdown += `\n`;
  }

  // Additional RFP Requirements & Agency Capability Responses
  if (profile.additionalRfpRequirements) {
    const rfp = profile.additionalRfpRequirements;
    markdown += `## ${sectionIndex}. Additional RFP Requirements & Agency Capability Responses\n\n`;
    sectionIndex++;

    if (rfp.rfpSummary) {
      markdown += `### RFP Executive Summary & Scope\n`;
      markdown += `${rfp.rfpSummary}\n\n`;
    }

    if (rfp.extractedMetadata) {
      const meta = rfp.extractedMetadata;
      markdown += `### Campaign Operational & Administrative Specifications\n`;
      if (meta.submissionDueDate) markdown += `- **Submission Due Date**: ${meta.submissionDueDate}\n`;
      if (meta.flightDates) markdown += `- **Flight Dates**: ${meta.flightDates}\n`;
      if (meta.budget) markdown += `- **Campaign Budget**: $${meta.budget.toLocaleString()}\n`;
      if (meta.paymentTerms) markdown += `- **Payment / Invoicing Terms**: ${meta.paymentTerms}\n`;
      if (meta.reportingRequirements && meta.reportingRequirements.length > 0) {
        markdown += `- **Reporting Schedule**: ${meta.reportingRequirements.join(", ")}\n`;
      }
      markdown += `\n`;
    }

    if (rfp.digitalRemedyCapabilityMatches && rfp.digitalRemedyCapabilityMatches.length > 0) {
      markdown += `### Specific RFP Questions & Digital Remedy Solutions\n\n`;
      rfp.digitalRemedyCapabilityMatches.forEach((match, i) => {
        markdown += `#### Ask ${i + 1}: ${match.rfpAsk}\n`;
        markdown += `- **Digital Remedy Solution**: ${match.digitalRemedySolution}\n`;
        markdown += `- **Execution & Capability Details**: ${match.capabilityDetails}\n`;
        markdown += `- **Capability Verification**: ${match.isSupported ? "Supported / Certified" : "Custom Configuration Required"}\n\n`;
      });
    }

    if (rfp.additionalNotes) {
      markdown += `### Additional RFP Process & Strategic Guidelines\n`;
      markdown += `${rfp.additionalNotes}\n\n`;
    }
  }

  return markdown;
}

export function exportSourcesToMarkdown(profile: AudienceProfile): string {
  let markdown = `# Citations & Sourcing Registry\n\n`;
  profile.sources.forEach((source, idx) => {
    markdown += `### [Source ${idx + 1}] ${source.name}\n`;
    markdown += `- **URL**: ${source.url}\n`;
    markdown += `- **Supported Claim**: ${source.supportedClaims}\n`;
    markdown += `- **Tier**: ${source.tier}\n`;
    markdown += `- **Usage**: ${source.usageType}\n\n`;
  });
  return markdown;
}
