import assert from "node:assert/strict";
import test from "node:test";
import { DEFAULT_DASHBOARD_CONFIG } from "../storage/types";
import { buildDashboard } from "../usage/dashboard";
import { formatMoney, kpiChange, presetDays, rangeFromDates, weeklySummaryText } from "./dashboardFormat";

test("money is compact for leadership: thousands as K, millions as M", () => {
  assert.equal(formatMoney(4_500), "$4,500");
  assert.equal(formatMoney(170_000), "$170K");
  assert.equal(formatMoney(3_240_000), "$3.2M");
  assert.equal(formatMoney(25_000_000), "$25M");
});

test("a change from zero reads as new rather than an infinite percentage", () => {
  assert.deepEqual(kpiChange({ value: 4, previous: 0 }), { label: "New", direction: "up" });
  assert.equal(kpiChange({ value: 0, previous: 0 }), null);
  assert.deepEqual(kpiChange({ value: 15, previous: 20 }), { label: "-25%", direction: "down" });
});

test("presets end today and include today", () => {
  const today = new Date(2026, 9, 14);
  assert.deepEqual(presetDays("7d", today), { fromDay: "2026-10-08", toDay: "2026-10-14" });
  assert.deepEqual(presetDays("qtd", today), { fromDay: "2026-10-01", toDay: "2026-10-14" });
  assert.deepEqual(presetDays("ytd", today), { fromDay: "2026-01-01", toDay: "2026-10-14" });
});

test("a date range covers whole days, so the last day's activity is counted", () => {
  const { from, to } = rangeFromDates("2026-10-01", "2026-10-01");
  assert.equal(Date.parse(to) - Date.parse(from), 24 * 60 * 60 * 1000 - 1);
});

test("the weekly summary leads with plans, budget and client reach, and ends with the link", () => {
  const data = buildDashboard([
    { id: "1", at: "2026-10-08T10:00:00.000Z", actor: "Ana", action: "plan_generate", ok: true, advertiserName: "Acme", budget: 250_000, channels: { "Connected TV": 150_000, Search: 100_000 } },
    { id: "2", at: "2026-10-09T10:00:00.000Z", actor: "Ana", action: "share_create", planId: "p" },
  ], "2026-10-07T00:00:00.000Z", "2026-10-13T23:59:59.999Z", DEFAULT_DASHBOARD_CONFIG);
  const text = weeklySummaryText(data, 1.5, "https://example.test/dashboard#key=dash_x");
  assert.match(text, /1 plan generated by 1 person/);
  assert.match(text, /\$250K in media budget planned across 1 advertiser/);
  assert.match(text, /About 1\.5 hours/);
  assert.match(text, /Largest media type: Connected TV \(\$150K\)/);
  assert.match(text, /Top planner: Ana/);
  assert.ok(text.trimEnd().endsWith("Full dashboard: https://example.test/dashboard#key=dash_x"));
});
