export function validateProductRegistry(records: MediaProductRecord[] = DIGITAL_REMEDY_PRODUCT_REGISTRY): string[] {
  const errors: string[] = [];
  const ids = new Set<string>();
  records.forEach((record) => {
    if (!record.id || ids.has(record.id)) errors.push(`Duplicate or missing product id: ${record.id || "(missing)"}`);
    ids.add(record.id);
    if (record.status !== "live" && record.recommendationEligible) errors.push(`${record.id} is not live but is recommendation eligible.`);
    if (!record.digitalRemedyExecutable && record.recommendationEligible) errors.push(`${record.id} is not executable but is recommendation eligible.`);
    if (record.minimumAllocationPercent < 0 || record.maximumAllocationPercent > 100 || record.minimumAllocationPercent > record.maximumAllocationPercent) {
      errors.push(`${record.id} has invalid allocation bounds.`);
    }
    if (record.minimumTotalSpend < 0 || record.minimumNormalized30DaySpend < 0 || record.minimumFlightDays < 1) {
      errors.push(`${record.id} has invalid product minimums.`);
    }
  });
  return errors;
}

export function findProductByAnyId(value: string): MediaProductRecord | undefined {
  const normalized = value.trim().toLowerCase();
  return DIGITAL_REMEDY_PRODUCT_REGISTRY.find((record) =>
    record.id.toLowerCase() === normalized ||
    record.legacyCanonicalId === normalized ||
    record.displayName.toLowerCase() === normalized ||
    record.aliases.some((alias) => alias.toLowerCase() === normalized),
  );
}
